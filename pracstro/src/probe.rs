use crate::celobj::CelObj;
use crate::coord::Position;
use crate::kepler::{self, JPLRawElements};
use InterplanetaryProbeState::*;

/// The state of a space probe
#[derive(Clone, Debug, PartialEq)]
pub enum InterplanetaryProbeState {
    /// In an orbit around the Sun
    Orbit(JPLRawElements),
    /// In an orbit around a Planet
    Planet(f64, &'static crate::sol::Planet),
    /// Crashed or Defunct
    Crashed(f64),
}
impl InterplanetaryProbeState {
    /// The epoch of any lifetime element
    pub fn start_date(&self) -> crate::time::Date {
        crate::time::Date::from_julian(match self {
            Orbit(o) => o.0,
            Planet(t, _) => *t,
            Crashed(t) => *t,
        })
    }
}

/// An interplanetary probe
#[derive(Clone, Debug, PartialEq)]
pub struct InterplanetaryProbe {
    /// The name of the Probe
    pub name: String,
    /// A list of orbital elements
    pub life: Vec<InterplanetaryProbeState>,
}

impl InterplanetaryProbe {
    /// Returns an index into the probes life
    pub fn index_of_date(&self, d: crate::time::Date) -> usize {
        let mut selected = self.life.len() - 1;

        if self.life[0].start_date() > d {
            panic!("Interplanetary Probe Position Queried for Date Before Epoch")
        }

        for i in 0..(self.life.len() - 1) {
            if self.life[i].start_date() <= d && self.life[i + 1].start_date() > d {
                selected = i;
                break;
            }
        }

        selected
    }
}

impl CelObj for InterplanetaryProbe {
    fn position(&self, d: crate::time::Date) -> crate::coord::Position {
        match self.life[self.index_of_date(d)] {
            Orbit(o) => {
                let r = kepler::kepl_obj(d, o);
                Position::from_polar_referenceobject_relative(r.coord, r.earthdist).geo_to_solar(d)
            }
            Planet(_, p) => p.position(d),
            Crashed(_) => panic!("Position Requested after its lifetime"),
        }
    }

    fn name(&self) -> String {
        self.name.clone()
    }

    fn brightness(&self, _: crate::time::Date) -> f64 {
        // Probes don't have brightness
        -99999.99999
    }
}

